#!/usr/bin/env python3
"""Independent adversarial/negative evaluation for RSTF.

benchmark/rstf/corpus.json and tools/rstf_benchmark.py are circular by
construction: the same encode_* helpers that generate the "attacks" are
the exact inverse of the decode_* logic that detects them, so a 99.4%
detection rate there proves internal consistency, not real-world efficacy.

This script runs against benchmark/rstf/adversarial_corpus.json instead,
which is hand-authored / drawn from independently-recalled reference
examples (see that file's per-example "note" fields for provenance) and
is never produced by calling api/semantic_fingerprint.py's encoders. It
also evaluates a negative/control set of legitimate non-English and
edge-case Latin text that the original benchmark never covered, because
its source corpus was 100% English ASCII.

Usage:

  python tools/rstf_adversarial_eval.py
  python tools/rstf_adversarial_eval.py --out-md benchmark/rstf/adversarial_report.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))
sys.path.insert(0, str(REPO_ROOT / "api"))

try:
    from api.semantic_fingerprint import FINGERPRINT_VERSION, compute_fingerprint
except Exception:
    from semantic_fingerprint import FINGERPRINT_VERSION, compute_fingerprint  # type: ignore

CORPUS_PATH = REPO_ROOT / "benchmark" / "rstf" / "adversarial_corpus.json"
REPORT_VERSION = "rstf-adversarial-eval-v0.1"

_RECEIPT_KEY = {
    "upside_down": "upside_down",
    "reversed": "reversed",
    "bidi_override": "bidi_override",
    "homoglyph": "homoglyph_substitution",
}


def run_eval() -> dict[str, Any]:
    corpus = json.loads(CORPUS_PATH.read_text(encoding="utf-8"))

    positive_results: list[dict[str, Any]] = []
    for example in corpus["positive_examples"]:
        fp = compute_fingerprint(example["text"])
        receipt_key = _RECEIPT_KEY[example["category"]]
        detected = fp["transform_receipt"].get(receipt_key, False)
        expected = example["expected_canonical_contains"]
        recovered = expected.lower() in fp["canonical_text"].lower()
        positive_results.append({
            "id": example["id"],
            "category": example["category"],
            "detected": detected,
            "recovered": recovered,
            "canonical_text": fp["canonical_text"],
            "expected_canonical_contains": expected,
        })

    negative_results: list[dict[str, Any]] = []
    for example in corpus["negative_examples"]:
        fp = compute_fingerprint(example["text"])
        negative_results.append({
            "id": example["id"],
            "category": example["category"],
            "false_positive": fp["transform_detected"],
            "transform_receipt": fp["transform_receipt"],
            "text": example["text"],
        })

    pos_count = len(positive_results)
    positive_summary = {
        "count": pos_count,
        "detection_rate": round(sum(r["detected"] for r in positive_results) / pos_count, 3) if pos_count else None,
        "recovery_rate": round(sum(r["recovered"] for r in positive_results) / pos_count, 3) if pos_count else None,
    }

    neg_count = len(negative_results)
    negative_summary = {
        "count": neg_count,
        "false_positive_rate": round(sum(r["false_positive"] for r in negative_results) / neg_count, 3) if neg_count else None,
    }
    negative_by_category: dict[str, dict[str, Any]] = {}
    for r in negative_results:
        bucket = negative_by_category.setdefault(r["category"], {"count": 0, "false_positives": 0})
        bucket["count"] += 1
        bucket["false_positives"] += int(r["false_positive"])
    for cat, bucket in negative_by_category.items():
        bucket["false_positive_rate"] = round(bucket["false_positives"] / bucket["count"], 3)

    return {
        "report_version": REPORT_VERSION,
        "fingerprint_version": FINGERPRINT_VERSION,
        "corpus_version": corpus.get("corpus_version"),
        "positive_summary": positive_summary,
        "negative_summary": negative_summary,
        "negative_by_category": negative_by_category,
        "positive_examples": positive_results,
        "negative_examples": negative_results,
        "truth_label": "independent_hand_authored_examples_not_generated_by_the_detectors_own_encoders",
    }


def render_markdown(report: dict[str, Any]) -> str:
    lines = [
        f"# RSTF independent adversarial eval ({report['report_version']})",
        "",
        f"Fingerprint version: `{report['fingerprint_version']}` | Corpus version: `{report['corpus_version']}`",
        "",
        "This corpus is hand-authored / drawn from independently-recalled reference "
        "examples, not generated by the module's own `encode_*` helpers — see "
        "`benchmark/rstf/adversarial_corpus.json` for provenance notes on every "
        "example, including where an initial recollection turned out to be "
        "unreliable and was corrected against arithmetic instead of asserted.",
        "",
        "## Positive examples (should be detected and recovered)",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Count | {report['positive_summary']['count']} |",
        f"| Detection rate | {report['positive_summary']['detection_rate']:.1%} |",
        f"| Recovery rate | {report['positive_summary']['recovery_rate']:.1%} |",
        "",
        "## Negative examples (should NOT be flagged — false-positive check)",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Count | {report['negative_summary']['count']} |",
        f"| False positive rate | {report['negative_summary']['false_positive_rate']:.1%} |",
        "",
        "### By category",
        "",
        "| Category | Count | False positive rate |",
        "|---|---|---|",
    ]
    for cat, stats in sorted(report["negative_by_category"].items()):
        lines.append(f"| `{cat}` | {stats['count']} | {stats['false_positive_rate']:.1%} |")

    failures = [r for r in report["positive_examples"] if not r["detected"] or not r["recovered"]]
    false_positives = [r for r in report["negative_examples"] if r["false_positive"]]

    lines += ["", "## Findings", ""]
    if not failures and not false_positives:
        lines.append("No misses, no false positives.")
    else:
        if failures:
            lines += ["### Missed positive examples", "",
                       "| id | category | detected | recovered | canonical_text |", "|---|---|---|---|---|"]
            for f in failures:
                lines.append(f"| {f['id']} | `{f['category']}` | {f['detected']} | {f['recovered']} | {f['canonical_text']!r} |")
        if false_positives:
            lines += ["", "### False positives on legitimate text", "",
                       "| id | category | text | transform_receipt |", "|---|---|---|---|"]
            for f in false_positives:
                lines.append(f"| {f['id']} | `{f['category']}` | {f['text']!r} | `{f['transform_receipt']}` |")

    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Run the independent RSTF adversarial eval")
    parser.add_argument("--out", help="Write the full JSON report to this path")
    parser.add_argument("--out-md", help="Write a human-readable Markdown report to this path")
    args = parser.parse_args()

    report = run_eval()

    if args.out:
        Path(args.out).write_text(json.dumps(report, indent=2, sort_keys=True), encoding="utf-8")
    if args.out_md:
        Path(args.out_md).write_text(render_markdown(report), encoding="utf-8")

    print(json.dumps(report, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
